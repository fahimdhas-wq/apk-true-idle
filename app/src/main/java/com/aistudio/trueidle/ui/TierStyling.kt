package com.aistudio.trueidle.ui

import androidx.annotation.ColorInt
import androidx.compose.runtime.Composable
import androidx.compose.runtime.remember
import androidx.compose.ui.graphics.Color
import com.aistudio.trueidle.core.TierConfig

/**
 * Presentation bridge between the pure-Kotlin [TierConfig] table and Android/Compose.
 *
 * `core` must stay free of Android types (enforced by `ArchitectureTest`), so the resolved Android
 * colour integers and the `@ColorInt` annotations live here instead of in the table itself. Nothing
 * in this file changes a tier's colour — it only converts the integers [TierConfig] already parsed
 * once at startup.
 *
 * No XML theme or `res/values/colors.xml` entry is generated on purpose: tier colours are data
 * (109 of them, generated by the progression), not a design-token palette, and duplicating them as
 * resources would create a second source of truth.
 */
object TierColors {

    /** Resolved ARGB colour for a tier identifier, or the neutral fallback for an unknown one. */
    @ColorInt
    fun colorInt(tier: String): Int = TierConfig.colorOf(tier)

    /** Resolved ARGB colour for a 1-based tier ordinal (equipment tier, promotion tier, rank). */
    @ColorInt
    fun colorIntForOrdinal(ordinal: Int): Int = TierConfig.colorForOrdinal(ordinal)

    /** Neutral fallback colour, for callers that need to name it explicitly. */
    @ColorInt
    val NEUTRAL_FALLBACK: Int = TierConfig.UNKNOWN_COLOR

    /** Compose form of [colorInt]. */
    fun color(tier: String): Color = Color(colorInt(tier))

    /** Compose form of [colorIntForOrdinal]. */
    fun colorForOrdinal(ordinal: Int): Color = Color(colorIntForOrdinal(ordinal))
}

/** Compose-friendly tier colour lookup; identical values, no per-frame parsing. */
@Composable
fun rememberTierColor(tier: String): Color {
    val resolved = remember(tier) { TierColors.colorInt(tier) }
    return remember(resolved) { Color(resolved) }
}

/** Compose-friendly tier colour lookup for a 1-based ordinal. */
@Composable
fun rememberTierColorForOrdinal(ordinal: Int): Color {
    val resolved = remember(ordinal) { TierColors.colorIntForOrdinal(ordinal) }
    return remember(resolved) { Color(resolved) }
}
